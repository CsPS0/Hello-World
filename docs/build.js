function getExtension(filename) {
    const parts = filename.split('.');
    if (parts.length < 2) return '';
    // Special multi-dot extension matching like .cljs.browser or .cljs.node
    const ext2 = '.' + parts.slice(1).join('.');
    if (EXTENSION_MAP[ext2]) return ext2;
    return '.' + parts.pop();
}

function main() {
    console.log(`Scanning ${SOURCE_DIR}...`);
    
    if (!fs.existsSync(SOURCE_DIR)) {
        console.error(`Source directory not found: ${SOURCE_DIR}`);
        process.exit(1);
    }

    const files = fs.readdirSync(SOURCE_DIR);
    const langs = [];

    files.forEach(filename => {
        const filepath = path.join(SOURCE_DIR, filename);
        if (!fs.statSync(filepath).isFile()) return;

        const relPath = `hello-world/${filename}`;

        if (FILENAME_MAP[filename]) {
            const entry = FILENAME_MAP[filename];
            langs.push({
                name: entry.name,
                description: entry.description || `Hello World in ${entry.name}`,
                path: relPath,
                tags: entry.tags
            });
            return;
        }

        const ext = getExtension(filename);
        if (EXTENSION_MAP[ext]) {
            const meta = EXTENSION_MAP[ext];
            const name = meta.name;
            const desc = DESCRIPTION_DEFAULTS[name] || `Hello World in ${name}`;
            langs.push({
                name: name,
                description: desc,
                path: relPath,
                tags: meta.tags
            });
        } else {
            console.log(`Unknown extension for file: ${filename}`);
        }
    });

    console.log(`Found ${langs.length} languages.`);

    // Load language_metadata.json if it exists
    let metadata = {};
    if (fs.existsSync(METADATA_PATH)) {
        console.log(`Loading metadata from ${METADATA_PATH}...`);
        try {
            metadata = JSON.parse(fs.readFileSync(METADATA_PATH, 'utf-8'));
        } catch (e) {
            console.error(`Error loading metadata: ${e.message}`);
        }
    }

    // Merge metadata
    langs.forEach(lang => {
        const name = lang.name;
        lang.slug = langSlug(name);
        lang.prism = PRISM_MAP[name] || PRISM_MAP[name.replace(/\s*\(.*\)$/, "")];
        if (!lang.prism) {
            console.error(`No syntax highlighting grammar for "${name}": add it to PRISM_MAP`);
            process.exit(1);
        }

        // Icon: docs/icons/<slug of base name>.svg, e.g. "Ruby (Script)" -> ruby.svg
        const iconFile = `${langSlug(name.replace(/\s*\(.*\)$/, ''))}.svg`;
        if (fs.existsSync(path.join(ICONS_DIR, iconFile))) {
            lang.icon = `icons/${iconFile}`;
        }
        // Fallbacks
        lang.creator = "Unknown";
        lang.year = "N/A";
        lang.history = "";
        lang.famousProjects = [];
        lang.frameworks = {};
        lang.quiz = {
            platforms: [],
            backend: false,
            typing: "dynamic",
            speed: "moderate"
        };

        if (metadata[name]) {
            const meta = metadata[name];
            lang.creator = meta.creator || "Unknown";
            lang.year = meta.year || "N/A";
            lang.history = meta.history || "";
            lang.famousProjects = meta.famousProjects || [];
            lang.frameworks = meta.frameworks || {};
            lang.quiz = meta.quiz || {
                platforms: [],
                backend: false,
                typing: "dynamic",
                speed: "moderate"
            };
        }

        // Official website; variants ("Ruby (Script)") fall back to the base language's site
        const baseMeta = metadata[name.replace(/\s*\(.*\)$/, "")];
        const website = (metadata[name] && metadata[name].website) || (baseMeta && baseMeta.website);
        if (website) {
            if (!/^https?:\/\//.test(website)) {
                console.error(`Website for "${name}" must start with http:// or https://`);
                process.exit(1);
            }
            lang.website = website;
        }
    });

    // Slugs are deep-link ids, so two languages must never share one
    const seen = new Map();
    langs.forEach(lang => {
        if (seen.has(lang.slug)) {
            console.error(`Duplicate slug "${lang.slug}": ${seen.get(lang.slug)} and ${lang.name}`);
            process.exit(1);
        }
        seen.set(lang.slug, lang.name);
    });

    // Sort by name case-insensitive
    langs.sort((a, b) => a.name.toLowerCase().localeCompare(b.name.toLowerCase()));

    console.log(`Writing ${OUTPUT_PATH}...`);
    fs.writeFileSync(OUTPUT_PATH, JSON.stringify(langs, null, 2), 'utf-8');
    console.log('Done.');
}

main();
