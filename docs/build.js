// URL-safe id used for deep links (#csharp) and icon files (icons/csharp.svg).
// "C#" -> "csharp", "C++" -> "cplusplus", "C--" -> "cminusminus", "F*" -> "fstar"
function langSlug(name) {
    return name.toLowerCase()
        .replace(/#/g, 'sharp')
        .replace(/\+/g, 'plus')
        .replace(/\*/g, 'star')
        .replace(/--/g, 'minusminus')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-|-$/g, '');
}

